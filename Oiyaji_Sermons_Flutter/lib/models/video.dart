class Video {
  final String id;
  final String title;
  final String description;
  final String duration;
  final DateTime date;
  final String url;
  final String thumbnail;

  Video({
    required this.id,
    required this.title,
    required this.description,
    required this.duration,
    required this.date,
    required this.url,
    required this.thumbnail,
  });
}